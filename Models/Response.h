#pragma once

// Тип ответа на действие пользователя. Его возвращают функции ввода из Hand.h
// (get_cell, wait) и Game::player_turn(), а Game::play() по нему решает, что делать дальше
enum class Response
{
    OK,     // «ничего особенного»: в Hand — значимого события пока нет, продолжаем ждать;
            // из player_turn() — игрок нормально завершил свой ход
    BACK,   // нажата кнопка «назад» (левый верхний угол) — откатить последний ход;
            // возможна, только если в истории есть хотя бы один ход
    REPLAY, // нажата кнопка «заново» (правый верхний угол) — начать новую партию
    QUIT,   // окно закрыто — завершить игру
    CELL    // клик по клетке доски; координаты клетки возвращаются вместе с ответом
};